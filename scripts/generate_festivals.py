def to_sql(records):
    def esc(v):
        if v is None:
            return "NULL"
        return "'" + str(v).replace("'", "''") + "'"

    titles = ", ".join(esc(r["title"]) for r in records)
    lines = [
        "-- 首批民俗节庆种子数据（C2），status=draft 待 admin 校对发布",
        "-- 幂等：按 category+title 先删后插",
        f"DELETE fd FROM festival_detail fd JOIN cultural_item ci ON fd.item_id = ci.id "
        f"WHERE ci.category = 'festival' AND ci.title IN ({titles});",
        f"DELETE FROM cultural_item WHERE category = 'festival' AND title IN ({titles});",
    ]
    for r in records:
        tags = json.dumps(r["tags"], ensure_ascii=False)
        lines.append(
            "INSERT INTO cultural_item (category, title, summary, content, region, "
            "image_url, image_anime_url, tags, sort_order, status, source) VALUES ("
            f"'festival', {esc(r['title'])}, {esc(r['summary'])}, {esc(r['content'])}, "
            f"{esc(r['region'])}, NULL, NULL, {esc(tags)}, 0, 'draft', 'ai');"
        )
        lines.append(
            "INSERT INTO festival_detail (item_id, festival_date, origin, customs, food) "
            f"SELECT id, {esc(r['festival_date'])}, {esc(r['origin'])}, {esc(r['customs'])}, "
            f"{esc(r['food'])} FROM cultural_item WHERE category = 'festival' "
            f"AND title = {esc(r['title'])} LIMIT 1;"
        )
    return "\n".join(lines) + "\n"


