import test from 'node:test'
import assert from 'node:assert/strict'
import { useHuluWorkshop } from '../src/composables/useHuluWorkshop.js'
import { createWorkshopState, getMotifPaths, saveWork } from '../src/utils/huluWorkshop.js'
const memory = () => {
  const values = new Map()
  return { getItem: key => values.get(key) || null, setItem: (key, value) => values.set(key, value) }
}
const mark = (kind = 'carve') => ({ kind, depth: 1, pigment: 'ink', points: [{ u: .4, v: .3 }, { u: .5, v: .32 }] })

test('工具和笔迹遵循制作阶段；撤销重做恢复原数据，新笔清除 redo', () => {
  const state = useHuluWorkshop(memory())
  assert.equal(state.selectTool('carve'), false)
  assert.equal(state.addStroke(mark()), false)
  assert.equal(state.enter(4), false)
  state.enter(2)
  assert.equal(state.selectTool('carve'), true)
  assert.equal(state.addStroke(mark()), true)
  state.undo()
  assert.equal(state.work.value.strokes.length, 0)
  state.redo()
  assert.deepEqual(state.work.value.strokes[0], mark())
  state.undo()
  state.addStroke(mark())
  assert.equal(state.canRedo.value, false)
})
test('更换坯形/构图明确确认才会清除笔迹，取消保留作品', () => {
  const state = useHuluWorkshop(memory())
  state.enter(2); state.addStroke(mark())
  assert.equal(state.choose('shape', 'full'), false)
  assert.equal(state.work.value.shape, 'balanced')
  state.cancelPending()
  assert.equal(state.work.value.strokes.length, 1)
  state.choose('motif', 'fish'); state.confirmPending()
  assert.equal(state.work.value.motif, 'fish')
  assert.equal(state.work.value.strokes.length, 0)
  assert.equal(state.step.value, 1)
})
test('撤销全部后换坯仍需清理历史，旧形制笔迹不能在新形制重做', () => {
  const state = useHuluWorkshop(memory())
  state.enter(2); state.addStroke(mark()); state.undo()
  state.choose('shape', 'full')
  assert.ok(state.pending.value)
  state.confirmPending()
  assert.equal(state.canRedo.value, false)
  state.redo()
  assert.equal(state.work.value.strokes.length, 0)
})
test('保存和恢复使用真实成品，草稿不覆盖已保存的作品', () => {
  const storage = memory()
  const completed = createWorkshopState()
  const paths = getMotifPaths(completed)
  completed.strokes = ['carve', 'coat', 'wipe'].flatMap(kind => paths.map(points => ({ kind, depth: 1, pigment: 'ink', points })))
  const entry = saveWork(storage, completed)
  const state = useHuluWorkshop(storage)
  assert.equal(state.save(), false)
  state.restore(entry.id)
  assert.equal(state.step.value, 4)
  assert.deepEqual(state.work.value, completed)
  state.choose('name', '梅枝试刻')
  assert.equal(state.save(), true)
  assert.equal(state.library.value.length, 1)
  assert.equal(state.library.value[0].work.name, '梅枝试刻')
  state.enter(2); state.addStroke(mark())
  state.restore(entry.id)
  assert.ok(state.pending.value, '恢复同一件作品也不能丢失未保存笔迹')
  state.cancelPending()
  assert.equal(state.work.value.strokes.length, completed.strokes.length + 1)
  state.remove(entry.id)
  assert.equal(state.library.value.length, 0)
})
