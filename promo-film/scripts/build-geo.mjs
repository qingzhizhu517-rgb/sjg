// Builds src/geo/shandong.js from the repo's own geodata, so the film's map is
// drawn from real boundaries instead of a painting:
//   - prefecture polygons: sjg-datav/src/assets/shandong.json (DataV, 16 cities)
//   - Yellow River course: sjg-datav/src/config/yellowRiver.ts (shared with datav / sandbox)
// The province outline is derived by edge counting: an edge used by exactly one
// prefecture ring lies on the provincial border or the coast.
//
//   node scripts/build-geo.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const repo = resolve(root, '..')
const geo = JSON.parse(readFileSync(resolve(repo, 'sjg-datav/src/assets/shandong.json'), 'utf8'))
const riverTs = readFileSync(resolve(repo, 'sjg-datav/src/config/yellowRiver.ts'), 'utf8')

const r4 = (v) => Math.round(v * 1e4) / 1e4

// ---- prefectures -------------------------------------------------------------
const cities = geo.features.map((f) => ({
  name: f.properties.name.replace(/市$/, ''),
  center: f.properties.center.map(r4),
  rings: f.geometry.coordinates.flatMap((poly) => poly.map((ring) => ring.map(([x, y]) => [r4(x), r4(y)]))),
}))

// ---- province outline by edge counting -------------------------------------
const key = ([x, y]) => `${x},${y}`
const edges = new Map()
for (const c of cities) {
  for (const ring of c.rings) {
    for (let i = 0; i < ring.length - 1; i++) {
      const a = key(ring[i])
      const b = key(ring[i + 1])
      if (a === b) continue
      const k = a < b ? `${a}|${b}` : `${b}|${a}`
      const e = edges.get(k)
      if (e) e.n++
      else edges.set(k, { n: 1, a: ring[i], b: ring[i + 1] })
    }
  }
}
const next = new Map()
for (const e of edges.values()) {
  if (e.n !== 1) continue
  const a = key(e.a)
  if (!next.has(a)) next.set(a, [])
  next.get(a).push(e.b)
}
const outline = []
const used = new Set()
for (const [start, outs] of next) {
  for (const first of outs) {
    const ek = `${start}>${key(first)}`
    if (used.has(ek)) continue
    const ring = [start.split(',').map(Number)]
    let cur = start
    let nxt = first
    used.add(ek)
    while (true) {
      ring.push(nxt)
      const nk = key(nxt)
      if (nk === start) break
      const cand = (next.get(nk) || []).find((p) => !used.has(`${nk}>${key(p)}`))
      if (!cand) break
      used.add(`${nk}>${key(cand)}`)
      cur = nk
      nxt = cand
    }
    void cur
    if (ring.length > 3) outline.push(ring)
  }
}
outline.sort((a, b) => b.length - a.length)

// ---- Yellow River ------------------------------------------------------------
const block = riverTs.split('export const YELLOW_RIVER_GEO')[1].split(']\n')[0]
const river = [...block.matchAll(/\[([\d.]+),\s*([\d.]+)\]/g)].map((m) => [Number(m[1]), Number(m[2])])
const nineBlock = riverTs.split('export const NINE_CITIES')[1]
const nine = [...nineBlock.matchAll(/name: '([^']+)', lon: ([\d.]+), lat: ([\d.]+)/g)]
  .map((m) => ({ name: m[1], lon: Number(m[2]), lat: Number(m[3]) }))
if (river.length < 10 || nine.length !== 9) throw new Error('yellowRiver.ts format changed')

const out = `// GENERATED by scripts/build-geo.mjs — do not edit by hand.
// Sources: sjg-datav/src/assets/shandong.json, sjg-datav/src/config/yellowRiver.ts
export const PREFECTURES = ${JSON.stringify(cities)}
export const OUTLINE = ${JSON.stringify(outline)}
export const YELLOW_RIVER = ${JSON.stringify(river)}
export const NINE_SITES = ${JSON.stringify(nine)}
`
mkdirSync(resolve(root, 'src/geo'), { recursive: true })
writeFileSync(resolve(root, 'src/geo/shandong.js'), out)
console.log(`prefectures ${cities.length} · outline rings ${outline.length} (main ${outline[0].length} pts) · river ${river.length} pts · ${(out.length / 1024).toFixed(0)} KB`)
